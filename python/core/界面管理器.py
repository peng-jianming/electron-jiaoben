"""
界面管理器 - 管理界面配置和按钮/状态
"""
from .动作管理器 import 动作管理器类


class 界面管理器类:
    """界面配置类，在初始化时直接将配置转换为对象属性访问"""

    def __init__(self, 界面名称, 配置字典, 控制器, 截图上下文, 字库集合, 模型):
        """
        初始化界面管理器

        参数:
            界面名称: 界面名称
            配置字典: 配置字典
            控制器: 设备控制器
            截图上下文: 截图上下文管理器
            字库集合: 字库
            模型: YOLO模型
        """
        self._名称 = 界面名称
        self._配置 = 配置字典

        # 动态创建按钮属性
        if '按钮' in 配置字典:
            self.按钮 = type('按钮集合', (), {})()
            for 名称, 配置 in 配置字典['按钮'].items():
                # 固定点击区域：配置为字符串 "x,y,w,h" 或原数组 [x,y,w,h]
                if isinstance(配置, (list, tuple)) and len(配置) == 4 and all(isinstance(x, (int, float)) for x in 配置):
                    字段 = 动作管理器类({"固定点击区域": 配置, "当前界面": 界面名称}, 控制器, 截图上下文)
                elif isinstance(配置, str) and 配置.count(",") == 3:
                    字段 = 动作管理器类({"固定点击区域": 配置, "当前界面": 界面名称}, 控制器, 截图上下文)
                else:
                    # 需要查找的按钮
                    字段配置 = {"查找字符串": f'{界面名称}_按钮_{名称}', "当前界面": 界面名称}
                    字段配置.update(配置)
                    字段 = 动作管理器类(字段配置, 控制器, 截图上下文)
                    字段.设置字库(字库集合).设置模型(模型)
                setattr(self.按钮, 名称, 字段)
        else:
            self.按钮 = type('按钮集合', (), {})()

        # 动态创建状态属性
        if '状态' in 配置字典:
            self.状态 = type('状态集合', (), {})()
            for 名称, 配置 in 配置字典['状态'].items():
                字段配置 = {"查找字符串": f'{界面名称}_状态_{名称}', "当前界面": 界面名称}
                字段配置.update(配置)
                字段 = 动作管理器类(字段配置, 控制器, 截图上下文)
                字段.设置字库(字库集合).设置模型(模型)
                setattr(self.状态, 名称, 字段)
        else:
            self.状态 = type('状态集合', (), {})()

    def 获取(self, 名称, 默认值=None):
        """兼容字典访问"""
        if 名称 == "按钮":
            return self.按钮
        if 名称 == "状态":
            return self.状态
        return self._配置.get(名称, 默认值)
