class 滑动区域操作类:
    """支持 界面.滑动查找区域.xxx.正向滑动() / 反向滑动() 执行一次区域拟人滑动"""

    def __init__(self, 控制器, 区域列表):
        """
        区域列表: [区域0字符串, 区域1字符串]，格式 "x,y,w,h"
        """
        self._控制器 = 控制器
        self._区域列表 = 区域列表

    def 正向滑动(self):
        """从区域下标 0 滑到 1，执行一次拟人滑动"""
        if self._区域列表 and len(self._区域列表) >= 2:
            self._控制器.拟人滑动_区域(self._区域列表[0], self._区域列表[1])

    def 反向滑动(self):
        """从区域下标 1 滑到 0，执行一次拟人滑动"""
        if self._区域列表 and len(self._区域列表) >= 2:
            self._控制器.拟人滑动_区域(self._区域列表[1], self._区域列表[0])

    def 按循环滑动(self, 上下文, 计数键="滑动循环次数", 每阶段次数=3):
        """
        按「反向×N → 正向×N → 正向×N → 反向×N」循环执行一次滑动，N 由 每阶段次数 控制，次数由 上下文[计数键] 记录。
        列表很长时可将 每阶段次数 调大（如 10），以便同方向多滑几次再换向。
        参数:
            上下文: 任务执行器传入的上下文字典，用于读写计数
            计数键: 在上下文中保存次数的键名，不同区域可用不同键以独立计数
            每阶段次数: 同一方向连续滑动的次数，默认 3；列表很长时可增大（如 5、10）
        """
        if not self._区域列表 or len(self._区域列表) < 2:
            return
        每阶段次数 = max(1, int(每阶段次数))
        次数 = 上下文.get(计数键, 0)
        阶段 = (次数 // 每阶段次数) % 4
        if 阶段 in (0, 3):
            self.反向滑动()
        else:
            self.正向滑动()
        上下文[计数键] = 次数 + 1


class 界面管理器类:
    """界面配置类，在初始化时直接将配置转换为对象属性访问"""

    def __init__(self, 界面名称, 配置字典, 控制器, 截图上下文, 字库集合, 模型):
        """
        初始化界面管理器

        参数:
            界面名称: 界面名称
            配置字典: 配置字典
            控制器: 设备控制器
            截图上下文: 截图上下文管理器
            字库集合: 字库
            模型: YOLO模型
        """
        self._名称 = 界面名称
        self._配置 = 配置字典

        # 动态创建按钮属性
        if '按钮' in 配置字典:
            self.按钮 = type('按钮集合', (), {})()
            for 名称, 配置 in 配置字典['按钮'].items():
                if isinstance(配置, str) and 配置.count(",") == 3:
                    字段 = 动作管理器类({"固定点击区域": 配置, "当前界面": 界面名称}, 控制器, 截图上下文)
                else:
                    # 需要查找的按钮
                    字段配置 = {"查找字符串": f'{界面名称}_按钮_{名称}', "当前界面": 界面名称}
                    字段配置.update(配置)
                    字段 = 动作管理器类(字段配置, 控制器, 截图上下文)
                    字段.设置字库(字库集合).设置模型(模型)
                setattr(self.按钮, 名称, 字段)
        else:
            self.按钮 = type('按钮集合', (), {})()

        # 动态创建状态属性
        if '状态' in 配置字典:
            self.状态 = type('状态集合', (), {})()
            for 名称, 配置 in 配置字典['状态'].items():
                字段配置 = {"查找字符串": f'{界面名称}_状态_{名称}', "当前界面": 界面名称}
                字段配置.update(配置)
                字段 = 动作管理器类(字段配置, 控制器, 截图上下文)
                字段.设置字库(字库集合).设置模型(模型)
                setattr(self.状态, 名称, 字段)
        else:
            self.状态 = type('状态集合', (), {})()

        if '滑动查找区域' in 配置字典:
            self.滑动查找区域 = type('滑动查找区域集合', (), {})()
            for 名称, 配置 in 配置字典['滑动查找区域'].items():
                # 支持 界面.滑动查找区域.活动面板.正向滑动() / 反向滑动()
                if isinstance(配置, (list, tuple)) and len(配置) >= 2 and 配置[0] and 配置[1]:
                    setattr(
                        self.滑动查找区域,
                        名称,
                        滑动区域操作类(控制器, [配置[0], 配置[1]]),
                    )
                else:
                    setattr(self.滑动查找区域, 名称, None)
        else:
            self.滑动查找区域 = type('滑动查找区域集合', (), {})()


    def 获取(self, 名称, 默认值=None):
        """兼容字典访问"""
        if 名称 == "按钮":
            return self.按钮
        if 名称 == "状态":
            return self.状态
        return self._配置.get(名称, 默认值)
