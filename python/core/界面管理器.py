class 滑动区域操作类:
    """支持 界面.滑动区域.xxx.正向滑动() / 反向滑动() 执行一次区域拟人滑动"""

    def __init__(self, 控制器, 区域, 更新数据, 界面名称):
        """
        区域: {起始区域: "x,y,w,h", 结束区域: "x,y,w,h"}
        """
        self.控制器 = 控制器
        self.更新数据 = 更新数据
        self.当前界面=界面名称
        self.区域 = 区域

    def 正向滑动(self, 日志=None):
        self.控制器.滑动(self.区域['起始区域'], self.区域['结束区域'])
        if 日志:
            self.更新数据("日志", f"{self.当前界面}: {日志}")

    def 反向滑动(self, 日志=None):
        """从区域下标 1 滑到 0，执行一次拟人滑动"""
        self.控制器.滑动(self.区域['结束区域'], self.区域['起始区域'])
        if 日志:
            self.更新数据("日志", f"{self.当前界面}: {日志}")

    def 按循环滑动(self, 上下文, 计数键="滑动循环次数", 每阶段次数=3, 日志=None):
        """
        按「反向×N → 正向×N → 正向×N → 反向×N」循环执行一次滑动，N 由 每阶段次数 控制，次数由 上下文[计数键] 记录。
        列表很长时可将 每阶段次数 调大（如 10），以便同方向多滑几次再换向。
        参数:
            上下文: 任务执行器传入的上下文字典，用于读写计数
            计数键: 在上下文中保存次数的键名，不同区域可用不同键以独立计数
            每阶段次数: 同一方向连续滑动的次数，默认 3；列表很长时可增大（如 5、10）
        """
        每阶段次数 = max(1, int(每阶段次数))
        次数 = 上下文.get(计数键, 0)
        阶段 = (次数 // 每阶段次数) % 4
        if 阶段 in (0, 3):
            self.反向滑动(日志)
        else:
            self.正向滑动(日志)
        上下文[计数键] = 次数 + 1


class 识字区域操作类:
    """支持 界面.识字区域.xxx.识别()，基于固定的 x,y,w,h 区域做 OCR"""

    def __init__(self, 截图上下文, 区域字符串):
        """
        区域字符串: "x,y,w,h"
        """
        self._截图上下文 = 截图上下文
        self._区域字符串 = 区域字符串
        self._x = self._y = self._w = self._h = None

        if isinstance(区域字符串, str):
            parts = [p.strip() for p in 区域字符串.split(",")]
            if len(parts) == 4:
                try:
                    self._x, self._y, self._w, self._h = map(int, parts)
                except ValueError:
                    # 解析失败则退回全图识别
                    self._x = self._y = self._w = self._h = None

        self._识字管理器 = 识字管理器类(截图上下文)

    def 识别(self, 是否新截图=False):
        """
        在预设区域内做 OCR 识别；若区域无效则退回全图识别。
        :return: 同 识字管理器类.识别 的返回结构
        """
        if (
            self._x is not None
            and self._y is not None
            and self._w is not None
            and self._h is not None
        ):
            return self._识字管理器.识别(
                x=self._x,
                y=self._y,
                w=self._w,
                h=self._h,
                是否新截图=是否新截图,
            )
        return self._识字管理器.识别(是否新截图=是否新截图)


class 界面管理器类:
    """界面配置类，在初始化时直接将配置转换为对象属性访问"""

    def __init__(self, 界面名称, 配置字典, 控制器, 截图上下文, 字库集合, 图片库集合, 模型, 更新数据):
        """
        初始化界面管理器

        参数:
            界面名称: 界面名称
            配置字典: 配置字典
            控制器: 设备控制器
            截图上下文: 截图上下文管理器
            字库集合: 字库
            图片库集合: 图片库（.npz 加载的模板字典）
            模型: YOLO模型
        """
        self._名称 = 界面名称
        self._配置 = 配置字典

        # 动态创建按钮属性
        if '按钮' in 配置字典:
            self.按钮 = type('按钮集合', (), {})()
            for 名称, 配置 in 配置字典['按钮'].items():
                字段配置 = {"查找字符串": f'{界面名称}_按钮_{名称}', "当前界面": 界面名称}
                字段配置.update(配置)
                字段 = 动作管理器类(字段配置, 控制器, 截图上下文, 更新数据)
                字段.设置字库(字库集合).设置图片库(图片库集合).设置模型(模型)
                setattr(self.按钮, 名称, 字段)
        else:
            self.按钮 = type('按钮集合', (), {})()

        # 动态创建状态属性
        if '状态' in 配置字典:
            self.状态 = type('状态集合', (), {})()
            for 名称, 配置 in 配置字典['状态'].items():
                字段配置 = {"查找字符串": f'{界面名称}_状态_{名称}', "当前界面": 界面名称}
                字段配置.update(配置)
                字段 = 动作管理器类(字段配置, 控制器, 截图上下文, 更新数据)
                字段.设置字库(字库集合).设置图片库(图片库集合).设置模型(模型)
                setattr(self.状态, 名称, 字段)
        else:
            self.状态 = type('状态集合', (), {})()

        if '滑动区域' in 配置字典:
            self.滑动区域 = type('滑动区域集合', (), {})()
            for 名称, 配置 in 配置字典['滑动区域'].items():
                # 支持 界面.滑动区域.活动面板.正向滑动() / 反向滑动()
                setattr(
                    self.滑动区域,
                    名称,
                    滑动区域操作类(控制器, 配置, 更新数据, self._名称),
                )
        else:
            self.滑动区域 = type('滑动区域集合', (), {})()

        # 动态创建识字区域属性，支持 界面.识字区域.等级.识别()
        if '识字区域' in 配置字典:
            self.识字区域 = type('识字区域集合', (), {})()
            for 名称, 配置 in 配置字典['识字区域'].items():
                if isinstance(配置, str) and 配置.count(",") == 3:
                    字段 = 识字区域操作类(截图上下文, 配置)
                else:
                    字段 = None
                setattr(self.识字区域, 名称, 字段)
        else:
            self.识字区域 = type('识字区域集合', (), {})()


    def 获取(self, 名称, 默认值=None):
        """兼容字典访问"""
        if 名称 == "按钮":
            return self.按钮
        if 名称 == "状态":
            return self.状态
        if 名称 == "滑动区域":
            return self.滑动区域
        if 名称 == "识字区域":
            return self.识字区域
        return self._配置.get(名称, 默认值)
