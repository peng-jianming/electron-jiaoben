def 是否在主界面不动(识别目标, 上下文, 超时时间 = 0):
    if 上下文["上次识别界面名"] != "主界面":
        return False
    结果列表 = 识别目标.识别文本列表(是否新截图=True)
    if len(结果列表) > 0:
        当前坐标 = 结果列表[0]
        现在 = time.monotonic()
        if (
            "坐标" in 上下文
            and "坐标相等开始时间" in 上下文
            and 上下文["坐标"] == 当前坐标
        ):
            return 现在 - 上下文["坐标相等开始时间"] > 超时时间
        else:
            上下文["坐标"] = 当前坐标
            上下文["坐标相等开始时间"] = 现在
    return False

