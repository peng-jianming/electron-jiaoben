def 注册全局界面():
    # 注意, 由于每一个任务界面状态机类的实例在运行时,都会有这些全局的注册界面,
    # 所以,这里的上下文为任务界面状态机类正在运行的实例的上下文.
    @任务界面状态机类.注册全局界面("未在游戏界面")
    def _(上下文, 界面):
        上下文["控制器"].adb.启动应用("com.netease.my")


    @任务界面状态机类.注册全局界面("选择区服界面")
    def _(上下文, 界面):
        # 轻享服_轻享一区_孙悟空
        区服信息 = 上下文["账号信息"].get("区服").split("_")
        服 = 区服信息[0]
        大区 = 区服信息[1]
        区 = 区服信息[2]

        if 服 == "轻享服":
            if not 界面.状态.选中轻享服.查找().是否找到():
                界面.按钮.轻享服.直接点击(日志="点击轻享服")

        if 服 == "正式服":
            if not 界面.状态.选中正式服.查找().是否找到():
                界面.按钮.正式服.直接点击(日志="点击正式服")

        结果列表 = 界面.识字区域.大区面板.识别(是否新截图=True);
        for 结果 in 结果列表:
            if 大区 in 结果["结果"]:
                上下文["控制器"].随机点击(f"{结果['x']},{结果['y']},{结果['w']},{结果['h']}")
            continue


        结果列表 = 界面.识字区域.区面板.识别(是否新截图=True)
        for 结果 in 结果列表:
            if 区 in 结果["结果"]:
                上下文["控制器"].随机点击(f"{结果['x']},{结果['y']},{结果['w']},{结果['h']}")
                结果列表2 = 界面.识字区域.区面板.识别(是否新截图=True)
                for 结果2 in 结果列表2:
                    if 结果2["结果"] == 上下文["账号信息"].get("名字"):
                        上下文["控制器"].随机点击(f"{结果2['x']},{结果2['y']},{结果2['w']},{结果2['h']}")
                        上下文["已确认账号信息"] = True
                        return


    @任务界面状态机类.注册全局界面("用户中心界面")
    def _(上下文, 界面):
        界面.按钮.切换账号.直接点击(日志="点击切换账号")


    @任务界面状态机类.注册全局界面("游戏登录界面")
    def _(上下文, 界面):
        if "已选择账号" in 上下文 and 上下文["已选择账号"]:
            界面.按钮.进入选择区服.直接点击(日志="点击进入选择区服")
        else:
            界面.按钮.进入选择账号.直接点击(日志="点击进入选择账号")
            上下文["已选择账号"] = False


    @任务界面状态机类.注册全局界面("选择账号界面")
    def _(上下文, 界面):
        if 界面.状态.出现账号列表.查找().是否找到():
            结果列表 = 界面.识字区域.账号列表.识别(是否新截图=True)
            
            for 结果 in 结果列表:
                if 上下文["账号信息"].get("账号") in 结果["结果"]:
                    上下文["控制器"].随机点击(f"{结果['x']},{结果['y']},{结果['w']},{结果['h']}")
                    return

        结果列表 = 界面.识字区域.当前账号.识别文本列表(是否新截图=True)
        if len(结果列表) != 1:
            return
        if 上下文["账号信息"].get("账号") in 结果列表[0]:
            界面.按钮.登录.直接点击(日志="点击登录")
            上下文["已选择账号"] = True
        else:
            界面.按钮.进入选择账号.直接点击(日志="点击进入选择账号")


def 确认账号信息(环境):
    # 确认账号是否跟当前运行的状态匹配
    # 如果未登录的就登录
    # 如果已经登录的直接查看信息
    # 如果信息匹配不上就退出退出重新登录
    任务界面状态机 = 任务界面状态机类(环境)
    注册全局界面()

    @任务界面状态机.注册界面("基础设置界面")
    def _(上下文, 界面):
        if 界面.状态.出现确认登出当前账号提示.查找().是否找到():
            界面.按钮.登出.直接点击(日志="点击登出")
            return

        结果列表 = 界面.识字区域.账号和服务器.识别文本列表(是否新截图=True)
        名字是否正确 = False
        服务器是否正确 = False
        区服信息 = 上下文["账号信息"].get("区服").split("_")
        服 = 区服信息[0]
        大区 = 区服信息[1]
        区 = 区服信息[2]
        for 结果 in 结果列表:
            if 上下文["账号信息"].get("名字") in 结果:
                名字是否正确 = True

            if 区 in 结果:
                服务器是否正确 = True
                
        print(名字是否正确, 服务器是否正确)
        if 名字是否正确 and 服务器是否正确:
            界面.按钮.关闭.直接点击(日志="关闭基础设置界面")
            任务界面状态机.结束()
        else:
            界面.按钮.切换账号.直接点击(日志="点击切换账号")

    @任务界面状态机.注册界面("主界面")
    def _(上下文, 界面):
        if "已确认账号信息" in 上下文 and 上下文["已确认账号信息"]:
            任务界面状态机.结束()
            return
        if 界面.按钮.系统.找到则点击(日志="点击系统"):
            return
        if 界面.按钮.展开工具.找到则点击(日志="点击展开工具"):
            return

    任务界面状态机.开始()


