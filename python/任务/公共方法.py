def 队伍组满人(环境, 任务目标, 目标等级=None, 地图名=None):
    任务界面状态机 = 任务界面状态机类(环境)

    if 地图名:
        前往地图(环境, 地图名)

    @任务界面状态机.注册界面("调整组队等级界面")
    def _(上下文, 界面):
        是否已选完任务目标 = False
        if 任务目标 == "三副本":
            是否已选完任务目标 = 界面.状态.已选中三副本.查找().是否找到()
        elif 任务目标 == "捉鬼任务":
            是否已选完任务目标 = 界面.状态.已选中抓鬼任务.查找().是否找到()

        if 是否已选完任务目标:
            结果列表 = 界面.识字区域.等级.识别文本列表(是否新截图=True)
            if len(结果列表) != 1:
                return
            try:
                if int(结果列表[0]) < 69:
                    界面.滑动区域.等级面板.正向滑动(日志="正向滑动等级面板")
                    return
                elif int(结果列表[0]) > 69:
                    界面.滑动区域.等级面板.反向滑动(日志="反向滑动等级面板")
                    return
                else:
                    界面.按钮.确定.直接点击(日志="点击确认按钮")
                    return
            except (ValueError, TypeError):
                return

        if 任务目标 == "三副本":
            if 界面.按钮.三副本.找到则点击(日志="点击三副本按钮"):
                return
            if 界面.按钮.副本任务.找到则点击(日志="点击副本任务按钮"):
                return
        elif 任务目标 == "捉鬼任务":
            if 界面.按钮.抓鬼任务.找到则点击(日志="点击抓鬼任务按钮"):
                return

        if 界面.按钮.日常任务.找到则点击(日志="点击日常任务按钮"):
            return

        界面.滑动区域.任务面板.按循环滑动(
            上下文, 计数键="队伍弹框界面进入次数", 每阶段次数=2, 日志="滑动任务面板"
        )

    @任务界面状态机.注册界面("队伍弹框界面")
    def _(上下文, 界面):
        if 界面.按钮.创建队伍.找到则点击(日志="点击创建队伍按钮"):
            return

        结果列表 = 界面.识字区域.目标等级.识别文本列表(是否新截图=True)
        if len(结果列表) != 2:
            return
        if 任务目标 not in 结果列表[0] or (目标等级 != None and 目标等级 not in 结果列表[1]):
            界面.按钮.选择等级.直接点击(日志="点击选择等级按钮")
            return

        if 界面.按钮.请离队伍.找到则点击(日志="请离离线队友"):
            return

        if 界面.按钮.离线队友.找到则点击(日志="点击离线队友"):
            return

        if 界面.按钮.暂离队友.找到则点击(日志="点击暂离队友"):
            return

        if 界面.状态.队伍没满.查找().是否找到():
            if 界面.按钮.自动匹配.找到则点击(日志="开启自动匹配队友"):
                return
            界面.按钮.一键喊话.直接点击(日志="队伍没满,点击一键喊话")
            界面.按钮.当前频道.直接点击(日志="选择当前频道")
            return

        界面.按钮.关闭.直接点击(日志="点击关闭队伍弹框")
        任务界面状态机.结束()

    @任务界面状态机.注册界面("主界面")
    def _(上下文, 界面):
        if 界面.状态.未选中队伍栏.找到则点击(日志="激活队伍栏或者打开队伍界面"):
            return

        if 界面.状态.已选中队伍栏.找到则点击(日志="打开队伍界面"):
            return

    任务界面状态机.开始()


def 清理背包(环境):
    任务界面状态机 = 任务界面状态机类(环境)
    任务界面状态机.更新上下文(初次进入包裹界面=True)
    任务界面状态机.更新上下文(包裹界面物品栏向上滑动次数=0)
    任务界面状态机.更新上下文(包裹界面物品栏向下滑动次数=0)

    @任务界面状态机.注册界面("主界面")
    def _(上下文, 界面):
        上下文["包裹界面物品栏向上滑动次数"] = 0
        上下文["包裹界面物品栏向下滑动次数"] = 0
        上下文["初次进入包裹界面"] = True
        界面.按钮.包裹.直接点击(日志="点击包裹按钮")

    @任务界面状态机.注册界面("临时道具栏界面")
    def _(上下文, 界面):
        界面.按钮.一键取回.直接点击(日志="点击一键取回按钮")
        上下文["已取回临时包裹物品"] = True

    @任务界面状态机.注册界面("包裹界面")
    def _(上下文, 界面):
        # 重置物品栏滚动到最上方
        if 上下文["初次进入包裹界面"] or (
            "已取回临时包裹物品" in 上下文 and 上下文["已取回临时包裹物品"]
        ):
            if 上下文["包裹界面物品栏向上滑动次数"] <= 6:
                界面.滑动区域.物品栏.反向滑动(日志="包裹界面物品栏滑动到最上方")
                上下文["包裹界面物品栏向上滑动次数"] += 1
                return
            上下文["初次进入包裹界面"] = False
            上下文["已取回临时包裹物品"] = False
            上下文["包裹界面物品栏向下滑动次数"] = 0
            return

        # 识别各种物品,识别到就清理,然后返回 TODO
        if (
            界面.按钮.阴阳草.找到则点击(日志="阴阳草")
            or 界面.按钮.不老根.找到则点击(日志="不老根")
            or 界面.按钮.月桂露.找到则点击(日志="月桂露")
        ):
            界面.按钮.收入.找到则点击(日志="点击收入", 新截图=True)
            return

        if "心魔宝珠批量使用次数用完" not in 上下文 and 界面.按钮.心魔宝珠.找到则点击(
            日志="心魔宝珠"
        ):
            界面.按钮.批量使用.找到则点击(日志="点击批量使用", 新截图=True)
            上下文["心魔宝珠批量使用次数用完"] = True
            return

        if 界面.按钮.百炼精铁.找到则点击(
            日志="百炼精铁"
        ) or 界面.按钮.制造书.找到则点击(日志="制造书"):
            界面.按钮.商会出售.找到则点击(日志="点击商会出售", 新截图=True)
            界面.按钮.出售.找到则点击(日志="点击出售", 新截图=True)
            return

        # 当前物品栏界面,没有识别到任何可以清理的物品,则向下滑动物品栏
        界面.滑动区域.物品栏.正向滑动(日志="包裹界面物品栏向下滑动")
        上下文["包裹界面物品栏向下滑动次数"] += 1
        # 当物品栏向下滚动6次,默认为滚动到最下方了,如果有未取回的临时包裹物品,则点击临时包裹按钮,否则关闭包裹界面
        if 上下文["包裹界面物品栏向下滑动次数"] >= 6:
            if 界面.按钮.临时包裹.找到则点击(日志="点击临时包裹按钮"):
                return
            存放仓库(环境)
            任务界面状态机.结束()

    任务界面状态机.开始()


