from core import 任务界面状态机类
import random


def 创建任务(环境):
    任务界面状态机 = 任务界面状态机类(环境)
    # 从第一个活跃奖励开始领取
    任务界面状态机.更新上下文(活跃奖励索引=1)

    @任务界面状态机.注册界面("活动界面")
    def _(上下文, 界面):
        # 默认从第一个开始，避免上下文异常
        if "活跃奖励索引" not in 上下文:
            上下文["活跃奖励索引"] = 1

        当前索引 = 上下文["活跃奖励索引"]

        # 五个奖励都处理完，直接关闭并结束任务
        if 当前索引 > 5:
            界面.按钮.关闭.直接点击(日志="全部活跃奖励已处理，关闭活动界面")
            任务界面状态机.结束()
            return

        # 根据索引只点击一个对应的奖励
        if 当前索引 == 1:
            界面.按钮.第一个活跃奖励.直接点击(日志="点击第一个活跃奖励")
        elif 当前索引 == 2:
            界面.按钮.第二个活跃奖励.直接点击(日志="点击第二个活跃奖励")
        elif 当前索引 == 3:
            界面.按钮.第三个活跃奖励.直接点击(日志="点击第三个活跃奖励")
        elif 当前索引 == 4:
            界面.按钮.第四个活跃奖励.直接点击(日志="点击第四个活跃奖励")
        elif 当前索引 == 5:
            界面.按钮.第五个活跃奖励.直接点击(日志="点击第五个活跃奖励")

        # 这一档领取完成，索引加一
        上下文["活跃奖励索引"] = 当前索引 + 1

        # 每次领取之后都退出活动界面，回到主界面
        界面.按钮.关闭.直接点击(日志="领取活跃奖励后关闭活动界面")

    @任务界面状态机.注册界面("主界面")
    def _(上下文, 界面):
        # 每次回到主界面都再次点活动，直到五档奖励全部处理完
        if "活跃奖励索引" in 上下文 and 上下文["活跃奖励索引"] > 5:
            # 已经处理完全部奖励，不再进入活动界面，直接结束
            任务界面状态机.结束()
            return
        界面.按钮.活动.直接点击(日志="点击活动按钮")

    任务界面状态机.开始()