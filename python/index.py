from 设置 import 服务器地址
from core.通信管理器 import 通信管理器类
from core.图像处理后端 import 图像处理后端类
from core.洪水填充后端 import 洪水填充后端类


class 主程序:
    def __init__(self):
        # 通信管理器：负责 socket.io 连接、消息转发与队列处理
        self.通信管理器 = 通信管理器类(
            服务器地址=服务器地址,
            消息处理回调=self.客户端消息队列处理,
        )
        # 图像处理模块
        self.图像处理后端 = 图像处理后端类(self.通信管理器)
        # 洪水填充模块（依赖图像处理模块的缓存与工具）
        self.洪水填充后端 = 洪水填充后端类(self.通信管理器, self.图像处理后端)

    def 客户端消息队列处理(self, 类型, 数据):
        """供通信管理器在消息队列线程中回调，处理单条消息。"""
        处理器 = {
            "图像上传缓存": self.图像处理后端.处理上传图片,
            "图像处理流水线": self.图像处理后端.处理图像处理流水线,
            "颜色过滤": self.图像处理后端.处理颜色过滤,
            "获取ADB设备列表": self.图像处理后端.处理获取ADB设备列表,
            "连接ADB设备": self.图像处理后端.处理连接ADB设备,
            "ADB截图": self.图像处理后端.处理ADB截图,
            "洪水填充上传缓存": self.洪水填充后端.处理上传图片,
            "洪水填充": self.洪水填充后端.处理洪水填充,
            "洪水填充动画": self.洪水填充后端.处理洪水填充动画,
        }
        if 类型 in 处理器:
            处理器[类型](数据)
        else:
            print(f"未知消息类型: {类型}")


if __name__ == "__main__":
    主程序()
