from 设置 import 服务器地址
from core.通信管理器 import 通信管理器类
from core.图像处理后端 import 图像处理后端类
from core.洪水填充后端 import 洪水填充后端类
from core.路线规划后端 import 路线规划后端类
from core.寻路测试后端 import 寻路测试后端类
from core.图像拼接后端 import 图像拼接后端类


class 主程序:
    def __init__(self):
        # 通信管理器：负责 socket.io 连接、消息转发与队列处理
        self.通信管理器 = 通信管理器类(
            服务器地址=服务器地址,
            消息处理回调=self.客户端消息队列处理,
        )
        # 图像处理模块
        self.图像处理后端 = 图像处理后端类(self.通信管理器)
        # 洪水填充模块（依赖图像处理模块的缓存与工具）
        self.洪水填充后端 = 洪水填充后端类(self.通信管理器, self.图像处理后端)
        # 路线规划模块（依赖图像处理模块的工具）
        self.路线规划后端 = 路线规划后端类(self.通信管理器, self.图像处理后端)
        # 寻路测试模块（依赖图像处理模块的工具）
        self.寻路测试后端 = 寻路测试后端类(self.通信管理器, self.图像处理后端)
        # 图像拼接模块（独立二值化+互相关拼接）
        self.图像拼接后端 = 图像拼接后端类(self.通信管理器)

    def 客户端消息队列处理(self, 类型, 数据):
        """供通信管理器在消息队列线程中回调，处理单条消息。"""
        # 图像处理 / 洪水填充 / 寻路 等模块的统一路由
        if 类型 == "图像上传缓存":
            self.图像处理后端.处理上传图片(数据)
        elif 类型 == "图像处理流水线":
            self.图像处理后端.处理图像处理流水线(数据)
        elif 类型 == "图像处理小地图":
            # 小地图帧同时走图像处理流水线与寻路模块的模板匹配
            self.图像处理后端.处理小地图图像(数据)
            self.寻路测试后端.处理小地图匹配(数据)
        elif 类型 == "颜色过滤":
            self.图像处理后端.处理颜色过滤(数据)
        elif 类型 == "获取ADB设备列表":
            self.图像处理后端.处理获取ADB设备列表(数据)
        elif 类型 == "连接ADB设备":
            self.图像处理后端.处理连接ADB设备(数据)
        elif 类型 == "ADB截图":
            self.图像处理后端.处理ADB截图(数据)
        elif 类型 == "洪水填充上传缓存":
            self.洪水填充后端.处理上传图片(数据)
        elif 类型 == "洪水填充上传base64缓存":
            self.洪水填充后端.处理上传base64图片(数据)
        elif 类型 == "洪水填充":
            self.洪水填充后端.处理洪水填充(数据)
        elif 类型 == "洪水填充动画":
            self.洪水填充后端.处理洪水填充动画(数据)
        elif 类型 == "路线规划上传缓存":
            self.路线规划后端.处理上传图片(数据)
        elif 类型 == "路线规划上传base64缓存":
            self.路线规划后端.处理上传base64图片(数据)
        elif 类型 == "路线规划获取骨干网":
            self.路线规划后端.处理获取骨干网(数据)
        elif 类型 == "路线规划计算":
            self.路线规划后端.处理寻路(数据)
        elif 类型 == "寻路测试上传缓存":
            self.寻路测试后端.处理上传图片(数据)
        elif 类型 == "寻路测试上传base64缓存":
            self.寻路测试后端.处理上传base64图片(数据)
        elif 类型 == "图像拼接":
            self.图像拼接后端.处理图像拼接(数据)
        else:
            print(f"未知消息类型: {类型}")


if __name__ == "__main__":
    主程序()
